export type ChapterKey = "tochi" | "standard" | "dialogue" | "after";

export type VoiceCardConfig = {
  /** voices.json の id。写真・家名・エリアはそちら側から取得される */
  id: string;
  /** 原文から切り出す引用（「」は自動で付与するので、引用符なしで入れる） */
  quote: string;
  /** 章カード用タグ（3〜4個） */
  tags: readonly string[];
  /** 使用する写真の index (0 始まり)。未指定なら [0] */
  photoIndices?: readonly number[];
};

export type ChapterConfig = {
  key: ChapterKey;
  /** 章ラベル（ローマ字小見出し） */
  label: string;
  /** 章番号（第一章〜第四章の和表記） */
  ordinal: string;
  /** 章のメインコピー（大見出し、Serif Light） */
  headline: string;
  /** 章の統計（Inter, accent 色） */
  stat: string;
  /** 章のリード文（Serif, 中サイズ） */
  lead: string;
  /** 章の声カード（4件想定） */
  voices: readonly VoiceCardConfig[];
  /** 章フッタの内訳 */
  breakdown: readonly { label: string; count: number }[];
};

